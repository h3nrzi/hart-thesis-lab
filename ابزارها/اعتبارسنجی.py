#!/usr/bin/env python3
# بررسی محلی ساختار پرونده‌ها؛ بدون تماس با اینترنت و بدون ایجاد تحلیل.
from pathlib import Path
import re
import sys

ریشه = Path(__file__).resolve().parent.parent
فایل‌های_لازم = [
    "README.md", "فهرست-تحلیل‌ها.md", "قواعد-مستندسازی.md",
    "راهنما/چرخه-کاری.md", "راهنما/معیارهای-ارزیابی.md",
    "راهنما/وضعیت‌ها.md", "الگوها/تحلیل-اولیه.md",
    "الگوها/به‌روزرسانی-مدرس.md", "الگوها/بازبینی-مستقل.md",
    "الگوها/ارزیابی-نتیجه.md", "تحلیل‌ها/README.md",
]
اشکال‌ها = []

for نام in فایل‌های_لازم:
    if not (ریشه / نام).is_file():
        اشکال‌ها.append(f"فایل ضروری موجود نیست: {نام}")

پوشه = ریشه / "تحلیل‌ها"
شمار = 0
if پوشه.is_dir():
    for پرونده in sorted(پوشه.iterdir()):
        if not پرونده.is_dir():
            continue
        شمار += 1
        if not re.fullmatch(r"[A-Za-z0-9_-]+", پرونده.name):
            اشکال‌ها.append(f"شناسه نامعتبر پرونده: {پرونده.name}")
        اولیه = پرونده / "تحلیل-اولیه.md"
        if not اولیه.is_file():
            اشکال‌ها.append(f"تحلیل اولیه موجود نیست: {پرونده.name}")
        else:
            متن = اولیه.read_text(encoding="utf-8")
            for عبارت in ("**شناسه ایده:**", "**نشانی منبع:**", "**زمان انتشار", "## ادعاهای مستقیم"):
                if عبارت not in متن:
                    اشکال‌ها.append(f"بخش «{عبارت}» در پرونده {پرونده.name} موجود نیست")
            if پرونده.name not in متن:
                اشکال‌ها.append(f"شناسه در متن تحلیل اولیه نیست: {پرونده.name}")
        for زیرپوشه in ("به‌روزرسانی‌ها", "برداشت‌ها", "ارزیابی‌ها"):
            مسیر = پرونده / زیرپوشه
            if not مسیر.is_dir():
                اشکال‌ها.append(f"پوشه رویداد موجود نیست: {مسیر.relative_to(ریشه)}")
                continue
            for سند in مسیر.glob("*.md"):
                if not re.fullmatch(r"\d{8}T\d{6}Z\.md", سند.name):
                    اشکال‌ها.append(f"نام رویداد باید زمان جهانی باشد: {سند.relative_to(ریشه)}")
                متن = سند.read_text(encoding="utf-8")
                if not متن.strip():
                    اشکال‌ها.append(f"رویداد خالی است: {سند.relative_to(ریشه)}")
                if "**شناسه ایده:**" not in متن:
                    اشکال‌ها.append(f"شناسه ایده در رویداد نیست: {سند.relative_to(ریشه)}")

if اشکال‌ها:
    print("کنترل ساختار ناموفق بود:")
    for مورد in اشکال‌ها:
        print(" -", مورد)
    sys.exit(1)
print(f"کنترل ساختار موفق بود. شمار پرونده‌های واقعی: {شمار}")
